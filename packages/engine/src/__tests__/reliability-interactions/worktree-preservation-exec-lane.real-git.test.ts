/*
FNXC:WorktreePreservation 2026-11-08-07:20 (RUFU-278):
The exec-lane reproduction the spec demands, and it is deliberately NOT the pinned-acquisition lane (which
`worktree-acquisition-pinned.test.ts` already covers). RUFU-260's card had its whole deliverable committed on
`fusion/<id>` while its checkout carried one untracked file the executor itself had generated. The removal door refused
to delete that unproven content — the FN-9233/FN-251 guarantee working exactly as designed — and the executor's
terminal sink then wrote that refusal as the card's `error` with `status: "failed"`, while a pointer clear nulled
`worktree`/`branch` even though the physical checkout and branch survived. Eight cards carried that sentence
(RUFU-178/186/210/253/260/262/263/265), and the retained checkout head-of-line blocked 14 more through the file-scope
dispatch gate.

Each test below drives real git through an execution-lane entry point, so the assertions cannot be satisfied by a
fixture that merely agrees with the production wording:
 - the refusal still happens and STILL deletes nothing (the safety half is not the bug);
 - the refusal no longer reaches the card as a terminal failure — it freezes through the sanctioned external-block
   primitive, which retains `worktree` and `branch` and is operator-clearable;
 - a genuine removal failure still fails exactly as before (the guard is not a maul).
*/

async function pathExists(path: string): Promise<boolean> {
  try {
    await access(path, fsConstants.F_OK);
    return true;
  } catch {
    return false;
  }
}

const roots: string[] = [];

afterEach(async () => {
  await Promise.all(roots.map((root) => rm(root, { recursive: true, force: true })));
  roots.length = 0;
});

/** A repo whose task branch carries a committed deliverable, plus the scratch file that triggers the refusal. */
async function setupTaskWorktree(options: { untracked: boolean }): Promise<{ root: string; worktreePath: string; branch: string }> {
  const root = await mkdtemp(join(tmpdir(), "fusion-rufu-278-"));
  roots.push(root);
  git(root, "git init -b main");
  git(root, 'git config user.email "test@example.com"');
  git(root, 'git config user.name "Test User"');
  await writeFile(join(root, "README.md"), "# repo\n", "utf-8");
  await writeFile(join(root, ".gitignore"), ".fusion/\ndist/\nnode_modules/\n", "utf-8");
  git(root, "git add README.md .gitignore");
  git(root, 'git commit -m "init"');
  await mkdir(join(root, ".worktrees"), { recursive: true });

  const branch = "fusion/rufu-278-repro";
  const worktreePath = join(root, ".worktrees", "rufu-278-repro");
  git(root, `git worktree add -b ${JSON.stringify(branch)} ${JSON.stringify(worktreePath)}`);
  // The deliverable: committed on the task branch, so it survives any worktree disposition.
  await writeFile(join(worktreePath, "deliverable.ts"), "export const shipped = true;\n", "utf-8");
  git(worktreePath, "git add deliverable.ts");
  git(worktreePath, 'git commit -m "feat: the deliverable"');
  if (options.untracked) {
    // Executor-generated scratch: untracked, not git-ignored, therefore unprovable and preserved by policy.
    await writeFile(join(worktreePath, ".gate-out.txt"), "generated by the verification runner\n", "utf-8");
  }
  return { root, worktreePath, branch };
}

function makeExecutorDeps(root: string, store: { logEntry: ReturnType<typeof vi.fn> }) {
  return {
    rootDir: root,
    store: store as never,
    reconcileSelfOwnedBeforeRemove: vi.fn().mockResolvedValue(undefined),
    hasActiveWorktreeBinding: () => false,
  };
}

describe.skipIf(!hasGit)("RUFU-278 exec lane: a preservation refusal keeps the card and its pointers", () => {
  it("refuses at the executor teardown seam and deletes nothing it could not prove", async () => {
    const { root, worktreePath, branch } = await setupTaskWorktree({ untracked: true });
    const store = { logEntry: vi.fn().mockResolvedValue(undefined), recordRunAuditEvent: vi.fn().mockResolvedValue(undefined) };

    await expect(
      removeOwnWorktreeWithReconcile(makeExecutorDeps(root, store), {
        worktreePath,
        settings: {} as never,
        taskId: "RUFU-278",
        reason: RemovalReason.CompletionLandedCleanup,
      }),
    ).rejects.toThrow(/preserving/);

    // The safety half: unproven content and the checkout it lives in are untouched.
    expect(await pathExists(join(worktreePath, ".gate-out.txt"))).toBe(true);
    expect(await pathExists(worktreePath)).toBe(true);
    // And so is the deliverable's branch — the card's actual work product.
    expect(git(root, `git rev-parse --verify ${JSON.stringify(branch)}`)).toMatch(/[0-9a-f]{7,}/);
  });

  it("records the settled protection on the card instead of only an engine-log failure line", async () => {
    const { root, worktreePath } = await setupTaskWorktree({ untracked: true });
    const store = { logEntry: vi.fn().mockResolvedValue(undefined), recordRunAuditEvent: vi.fn().mockResolvedValue(undefined) };

    await expect(
      removeOwnWorktreeWithReconcile(makeExecutorDeps(root, store), {
        worktreePath,
        settings: {} as never,
        taskId: "RUFU-278",
        reason: RemovalReason.CompletionLandedCleanup,
      }),
    ).rejects.toThrow(/preserving/);

    const sentences = store.logEntry.mock.calls.map((call) => String(call[1]));
    expect(sentences.some((line) => /preserved/i.test(line))).toBe(true);
    // The operator needs the path to collect the work; the audit row must not carry it.
    expect(sentences.some((line) => line.includes(worktreePath))).toBe(true);
    const auditEvent = store.recordRunAuditEvent.mock.calls[0]?.[0];
    expect(auditEvent?.metadata?.classification).toBe("deliverable");
    expect(JSON.stringify(auditEvent?.metadata ?? {})).not.toContain(worktreePath);
  });

  it("freezes through the external-block primitive at the terminal sink instead of writing status failed", async () => {
    const { root, worktreePath, branch } = await setupTaskWorktree({ untracked: true });
    const refusal = await removeOwnWorktreeWithReconcile(
      makeExecutorDeps(root, { logEntry: vi.fn().mockResolvedValue(undefined), recordRunAuditEvent: vi.fn().mockResolvedValue(undefined) }),
      { worktreePath, settings: {} as never, taskId: "RUFU-278", reason: RemovalReason.CompletionLandedCleanup },
    ).then(() => null, (error: unknown) => error);
    expect(refusal).toBeInstanceOf(Error);

    const live = {
      column: "in-progress",
      effectiveNodeId: "step-execute",
      currentStep: 1,
      worktree: worktreePath,
      branch,
    };
    const updateTask = vi.fn().mockResolvedValue(undefined);
    const deps = {
      store: {
        getTask: vi.fn().mockResolvedValue(live),
        updateTask,
        logEntry: vi.fn().mockResolvedValue(undefined),
        recordRunAuditEvent: vi.fn().mockResolvedValue(undefined),
      },
      getRunContextFor: () => undefined,
    };

    const parked = await parkPreservedWorktreeObstacle(deps as never, "RUFU-278", refusal);

    expect(parked).toBe(true);
    const patch = updateTask.mock.calls[0]?.[1] as Record<string, unknown>;
    // The terminal badge RUFU-260 wore is now an operator-clearable freeze instead.
    expect(patch.status).toBe("blocked");
    expect(patch.status).not.toBe("failed");
    expect(patch.pausedReason).toBe("external-block");
    expect(String(patch.error)).toContain("WORKTREE_CONTENT_PRESERVED");
    // A freeze names the preserved checkout in its resume pointer and never nulls a pointer.
    const block = patch.externalBlock as { resume: Record<string, unknown>; origin: string; code: string };
    expect(block.origin).toBe("project-configuration");
    expect(block.resume.worktree).toBe(worktreePath);
    expect(block.resume.branch).toBe(branch);
    expect(Object.keys(patch)).not.toContain("worktree");
    expect(Object.keys(patch)).not.toContain("branch");
    // The physical checkout and its unproven content are still on disk after the freeze.
    expect(await pathExists(join(worktreePath, ".gate-out.txt"))).toBe(true);
  });

  it("declines a genuine removal failure so the card still fails exactly as before", async () => {
    const updateTask = vi.fn().mockResolvedValue(undefined);
    const deps = {
      store: {
        getTask: vi.fn().mockResolvedValue({ column: "in-progress", effectiveNodeId: "step-execute", currentStep: 0, worktree: "/repo/.worktrees/x", branch: "fusion/x" }),
        updateTask,
        logEntry: vi.fn().mockResolvedValue(undefined),
        recordRunAuditEvent: vi.fn().mockResolvedValue(undefined),
      },
      getRunContextFor: () => undefined,
    };

    const parked = await parkPreservedWorktreeObstacle(
      deps as never,
      "RUFU-278",
      new Error("Worktree acquisition failed: git worktree remove exited 128"),
    );

    expect(parked).toBe(false);
    expect(updateTask).not.toHaveBeenCalled();
  });

  it("declines the project-root refusal: a misconfiguration is never parked as a preservation", async () => {
    const updateTask = vi.fn().mockResolvedValue(undefined);
    const deps = {
      store: {
        getTask: vi.fn().mockResolvedValue({ column: "in-progress", effectiveNodeId: "step-execute", currentStep: 0, worktree: "/repo", branch: "main" }),
        updateTask,
        logEntry: vi.fn().mockResolvedValue(undefined),
        recordRunAuditEvent: vi.fn().mockResolvedValue(undefined),
      },
      getRunContextFor: () => undefined,
    };

    const parked = await parkPreservedWorktreeObstacle(
      deps as never,
      "RUFU-278",
      new Error("preserving /repo: refusing to remove the project root checkout"),
    );

    expect(parked).toBe(false);
    expect(updateTask).not.toHaveBeenCalled();
  });

  it("removes the worktree when the unproven file is gone, proving the refusal was the only obstacle", async () => {
    const { root, worktreePath } = await setupTaskWorktree({ untracked: true });
    const store = { logEntry: vi.fn().mockResolvedValue(undefined), recordRunAuditEvent: vi.fn().mockResolvedValue(undefined) };
    const teardown = {
      worktreePath,
      settings: {} as never,
      taskId: "RUFU-278",
      reason: RemovalReason.CompletionLandedCleanup,
    };

    await expect(
      removeOwnWorktreeWithReconcile(makeExecutorDeps(root, store), teardown),
    ).rejects.toThrow(/preserving/);

    // The operator remedy: move the scratch file out, and the same teardown call succeeds unchanged.
    await rm(join(worktreePath, ".gate-out.txt"), { force: true });
    await expect(
      removeOwnWorktreeWithReconcile(makeExecutorDeps(root, store), teardown),
    ).resolves.toBeUndefined();
    expect(await pathExists(worktreePath)).toBe(false);
  });

  /*
  FNXC:WorktreePreservation 2026-11-08-08:00 (RUFU-278 Step 6 premise check):
  The card's premise, read off the removal door instead of asserted in prose: a task whose deliverable is fully
  committed and whose checkout holds nothing but regenerable ignored output is NOT a preservation case at all. Strict
  end-of-task cleanup removes it and records no worktree:removal-preserved row. RUFU-260 therefore cannot have been
  refused for its committed work or for its build output — the refusal needs content the probe cannot prove disposable,
  which is exactly the scratch file the reproduction above plants. This test is read-only evidence; it resurrects
  nothing and mutates no card.
  */
  it("premise check: strict landed cleanup of a committed deliverable with only regenerable output removes and records no preservation", async () => {
    const { root, worktreePath } = await setupTaskWorktree({ untracked: false });
    await mkdir(join(worktreePath, "dist"), { recursive: true });
    await writeFile(join(worktreePath, "dist", "bundle.js"), "generated\n", "utf-8");
    const gitAudit = vi.fn().mockResolvedValue(undefined);

    await expect(
      removeWorktree({
        rootDir: root,
        worktreePath,
        settings: {},
        reason: RemovalReason.CompletionLandedCleanup,
        audit: { git: gitAudit } as never,
      }),
    ).resolves.toMatchObject({ removed: true });

    expect(await pathExists(worktreePath)).toBe(false);
    const preservationRows = gitAudit.mock.calls.filter((call) => (call[0] as { type?: string })?.type === "worktree:removal-preserved");
    expect(preservationRows).toHaveLength(0);
  });
});
